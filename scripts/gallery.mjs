// Only keys a live app can store and apply, on either engine. Level colours
// (silverColor, goldColor, platinumColor) and levelsOrder are left out on
// purpose: restyling the levels could make "Private" look like the lesser
// choice. Widget-only keys (spacingSize, navigationStyle, ...) are left out
// because copying them to a live app would silently do nothing.
const ALLOWED = new Set([
  'textSize', 'headingSize', 'animationSpeed', 'position', 'displayType', 'marginSize',
  'revokePosition', 'revokeMarginX', 'revokeMarginY', 'animation', 'showDuration',
  'textColor', 'headingColor', 'primaryColor', 'borderColor', 'bannerOpacity',
  'bannerColor', 'btnTextColor', 'btnBorderRadius',
]);
// Every example sets these, so each screenshot shows a complete, intended look
// rather than a mix of the example and the widget defaults.
const REQUIRED = ['bannerOpacity', 'textColor', 'headingColor', 'primaryColor',
  'btnTextColor', 'bannerColor', 'borderColor', 'btnBorderRadius', 'textSize', 'headingSize'];
// The widget has CSS for these values only; anything else renders unstyled.
const ENUMS = {
  position: ['bottom', 'top', 'left', 'right', 'center'],
  displayType: ['floating', 'fixed'],
  animation: ['fade', 'slide'], // as the MCP design schema accepts
  revokePosition: ['bottom-left', 'bottom-right'],
};
// v2 only: the one config key an example may set. It is a config key, not a design key.
const BANNER_STYLES = ['standard', 'compact'];
// Screenshot sizes. Desktop is the default; "phone" shows the narrow-screen layout.
const VIEWPORTS = {
  desktop: { viewport: { width: 1280, height: 800 }, deviceScaleFactor: 1 },
  phone: { viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 },
};
// The unselected level pills always sit on this background in v1: it is fixed
// in the widget's stylesheet (its inactive-pill colour), and no design key changes it.
const INACTIVE_PILL_BG = '#ffffff';
const HEX = /^#[0-9a-f]{6}$/i; // the widget replaces any other colour format with its default
const LENGTH = /^\d+(\.\d+)?px$/;
const COLOR_KEYS = ['textColor', 'headingColor', 'primaryColor', 'borderColor', 'bannerColor', 'btnTextColor'];
const LENGTH_KEYS = ['textSize', 'headingSize', 'marginSize', 'revokeMarginX', 'revokeMarginY', 'btnBorderRadius'];

// WCAG 2 relative luminance and contrast ratio.
function luminance(hex) {
  const [r, g, b] = [1, 3, 5].map((i) => {
    const c = parseInt(hex.slice(i, i + 2), 16) / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}
function contrast(a, b) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}
// The colour a visitor sees when fg is drawn at `alpha` opacity over bg.
function blend(fg, bg, alpha) {
  return '#' + [1, 3, 5].map((i) => {
    const c = alpha * parseInt(fg.slice(i, i + 2), 16) + (1 - alpha) * parseInt(bg.slice(i, i + 2), 16);
    return Math.round(c).toString(16).padStart(2, '0');
  }).join('');
}

// Every colour pair a visitor has to read on the first layer, as
// [foreground label, hex, background label, hex, minimum ratio].
function contrastPairs(ex) {
  const d = ex.design;
  if (ex.engine === 'v1') {
    // WCAG AA for normal text. The selected level pill renders the btnTextColor
    // label on secondaryColor, which falls back to borderColor in the widget's
    // stylesheet, so a label colour chosen for the button must also be checked
    // on borderColor.
    const pairs = [['textColor', 'bannerColor'], ['headingColor', 'bannerColor'],
      ['btnTextColor', 'primaryColor'], ['btnTextColor', 'borderColor'],
      // The widget's stylesheet also uses primaryColor as a text colour: the
      // Customize, Privacy policy and Do Not Sell links sit on bannerColor.
      ['primaryColor', 'bannerColor']]
      .map(([fg, bg]) => [fg, d[fg], bg, d[bg], 4.5]);
    // The unselected level labels are drawn in borderColor on INACTIVE_PILL_BG.
    pairs.push(['borderColor (unselected level label)', d.borderColor, 'the inactive pill background', INACTIVE_PILL_BG, 4.5]);
    return pairs;
  }
  // v2: every element below sits directly on the panel, which is bannerColor.
  const pairs = [
    ['textColor', d.textColor, 'bannerColor (body text)', d.bannerColor, 4.5], // the message paragraph
    ['headingColor', d.headingColor, 'bannerColor (heading)', d.bannerColor, 4.5], // the notice heading
    ['headingColor', d.headingColor, 'bannerColor (unselected level label)', d.bannerColor, 4.5], // level pills are transparent
    ['textColor', d.textColor, 'bannerColor (Customize)', d.bannerColor, 4.5], // Customize is a transparent button
    ['primaryColor', d.primaryColor, 'bannerColor (links)', d.bannerColor, 4.5], // Privacy policy, Do Not Sell, and compact's phone Customize link
    ['btnTextColor', d.btnTextColor, 'primaryColor (selected level label)', d.primaryColor, 4.5], // a chosen pill fills with primaryColor
    ['borderColor', d.borderColor, 'bannerColor (level pill border)', d.bannerColor, 3], // non-text: WCAG 1.4.11 asks 3:1
  ];
  // The Global Privacy Control note, both styles: shown when the visitor sends GPC. Drawn at 0.85 opacity.
  if (HEX.test(d.textColor ?? '') && HEX.test(d.bannerColor ?? '')) {
    pairs.push(['textColor at 0.85 opacity', blend(d.textColor, d.bannerColor, 0.85), 'bannerColor (GPC note)', d.bannerColor, 4.5]);
  }
  // The site's domain, top left: standard only (compact puts the heading there). Drawn at 0.7 opacity.
  if (ex.config?.bannerStyle === 'standard' && HEX.test(d.textColor ?? '') && HEX.test(d.bannerColor ?? '')) {
    pairs.push(['textColor at 0.7 opacity', blend(d.textColor, d.bannerColor, 0.7), 'bannerColor (site domain)', d.bannerColor, 4.5]);
  }
  return pairs;
}

const imageRel = (ex) => `${ENGINES[ex.engine].dir}/img/${ex.id}.png`;
const imagePath = (ex) => join(root, imageRel(ex));

function validate({ needImages }) {
  const errors = [];
  const ids = new Set();
  for (const ex of all) {
    const where = `example "${ex.id}"`;
    if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(ex.id ?? '')) errors.push(`${where}: id must be a lowercase slug`);
    if (ids.has(ex.id)) errors.push(`${where}: duplicate id`);
    ids.add(ex.id);
    if (!(ex.engine in ENGINES)) {
      errors.push(`${where}: engine must be one of ${Object.keys(ENGINES).join('|')}`);
      continue; // everything below depends on the engine
    }
    for (const f of ['title', 'caption', 'alt']) {
      if (typeof ex[f] !== 'string' || !ex[f].trim()) errors.push(`${where}: missing ${f}`);
    }
    for (const f of ['background', 'text', 'accent']) {
      if (!HEX.test(ex.site?.[f] ?? '')) errors.push(`${where}: site.${f} must be #rrggbb`);
    }
    if ('viewport' in ex && ex.viewport !== 'phone') errors.push(`${where}: viewport must be "phone" (or left out for desktop)`);
    // bannerStyle exists only in v2; v1 would ignore it, so a v1 example carrying it would mislead.
    if (ex.engine === 'v1' && 'config' in ex) errors.push(`${where}: config is v2 only (v1 has no bannerStyle)`);
    if (ex.engine === 'v2') {
      const c = ex.config ?? {};
      for (const k of Object.keys(c)) {
        if (k !== 'bannerStyle') errors.push(`${where}: config key "${k}" is not allowed (only bannerStyle)`);
      }
      if (!BANNER_STYLES.includes(c.bannerStyle)) errors.push(`${where}: config.bannerStyle must be one of ${BANNER_STYLES.join('|')}`);
    }
    const d = ex.design ?? {};
    for (const k of Object.keys(d)) {
      if (!ALLOWED.has(k)) errors.push(`${where}: design key "${k}" is not allowed`);
    }
    for (const k of REQUIRED) {
      if (!(k in d)) errors.push(`${where}: design.${k} is required`);
    }
    for (const [k, values] of Object.entries(ENUMS)) {
      if (k in d && !values.includes(d[k])) errors.push(`${where}: design.${k} must be one of ${values.join('|')}`);
    }
    for (const k of COLOR_KEYS) {
      if (k in d && !HEX.test(d[k])) errors.push(`${where}: design.${k} must be #rrggbb`);
    }
    for (const k of LENGTH_KEYS) {
      if (k in d && !LENGTH.test(d[k])) errors.push(`${where}: design.${k} must be a px length`);
    }
    if ('animationSpeed' in d && !/^\d+(\.\d+)?s$/.test(d.animationSpeed)) errors.push(`${where}: design.animationSpeed must be in seconds`);
    if ('showDuration' in d && typeof d.showDuration !== 'boolean') errors.push(`${where}: design.showDuration must be true or false`);
    // Below 1, the page shows through the banner, so the contrast figures
    // below would not be what a visitor actually sees.
    if (d.bannerOpacity !== 1) errors.push(`${where}: design.bannerOpacity must be 1`);
    for (const [fg, fgHex, bg, bgHex, min] of contrastPairs({ ...ex, design: d })) {
      if (!HEX.test(fgHex ?? '') || !HEX.test(bgHex ?? '')) continue;
      const ratio = contrast(fgHex, bgHex);
      if (ratio < min) errors.push(`${where}: ${fg} on ${bg} contrast is ${ratio.toFixed(2)}:1, below WCAG AA ${min}:1`);
    }
    // The pages show the image; a missing one would publish a broken gallery.
    if (needImages && !existsSync(imagePath(ex))) errors.push(`${where}: missing ${imageRel(ex)} (run: node scripts/gallery.mjs render ${ex.id})`);
  }
  // A PNG with no example would be published to the site but shown nowhere.
  if (needImages) {
    for (const [engine, { dir }] of Object.entries(ENGINES)) {
      const own = new Set(examplesOf(engine).map((ex) => ex.id));
      const imgDir = join(root, dir, 'img');
      for (const f of existsSync(imgDir) ? readdirSync(imgDir) : []) {
        if (f.endsWith('.png') && !own.has(f.slice(0, -4))) errors.push(`orphan image ${dir}/img/${f}: no ${engine} example has id "${f.slice(0, -4)}" (delete it)`);
      }
    }
  }
  if (errors.length) {
    console.error('gallery: validation failed\n  ' + errors.join('\n  '));
    process.exit(1);
  }
}

// Width and height from the PNG header (IHDR), so <img> sizes always match the file.
function pngSize(ex) {
  const buf = readFileSync(imagePath(ex));
  return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
}

