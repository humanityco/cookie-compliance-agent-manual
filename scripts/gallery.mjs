async function render(ids) {
  validate({ needImages: false }); // never screenshot a design the build would reject
  let playwright;
  try {
    playwright = createRequire(import.meta.url)('playwright');
  } catch {
    console.error('gallery render needs playwright. Install it with: npm i playwright (then: npx playwright install chromium)');
    process.exit(1);
  }
  const unknown = ids.filter((id) => !all.some((ex) => ex.id === id));
  if (unknown.length) {
    console.error(`gallery: unknown example id(s): ${unknown.join(', ')}`);
    process.exit(1);
  }
  const chosen = ids.length ? all.filter((ex) => ids.includes(ex.id)) : all;
  const browser = await playwright.chromium.launch();
  // The v1 widget does not start for automated browsers: it checks
  // navigator.webdriver and a "HeadlessChrome/" user agent. Present as a normal
  // desktop Chrome so the preview renders. (v2 checks neither; this is harmless there.)
  const userAgent = `Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/${browser.version()} Safari/537.36`;
  let failed = false;
  try {
    for (const ex of chosen) {
      const context = await browser.newContext({ ...VIEWPORTS[ex.viewport ?? 'desktop'], userAgent });
      await context.addInitScript(() => Object.defineProperty(Navigator.prototype, 'webdriver', { get: () => false }));
      const page = await context.newPage();
      // Served from a placeholder origin, not page.setContent: about:blank has no
      // cookie access, and the widget stops when reading document.cookie throws.
      if (ex.engine === 'v1') {
        await page.route(PAGE_URL, (route) => route.fulfill({ contentType: 'text/html', body: mockPage(ex) }));
      } else {
        await page.route('**/*', (route) => {
          const url = route.request().url();
          if (url === PAGE_URL) return route.fulfill({ contentType: 'text/html', body: mockPage(ex) });
          if (url === ENGINES.v2.widget) return route.continue();
          if (new URL(url).pathname === V2_CONFIG_PATH) return route.fulfill({ contentType: 'application/json', body: JSON.stringify(v2Config(ex)) });
          return route.abort();
        });
      }
      try {
        await page.goto(PAGE_URL, { waitUntil: 'load' });
        // A visitor's Global Privacy Control signal changes what the v2 banner shows.
        if (await page.evaluate(() => navigator.globalPrivacyControl === true)) throw new Error('the browser is sending Global Privacy Control');
        // The banner's root container is #hu; wait inside it, not on the document.
        const banner = page.locator('#hu');
        await banner.waitFor({ state: 'visible', timeout: 20000 });
        await banner.locator('button').first().waitFor({ state: 'visible', timeout: 10000 });
        // Let the entrance animation finish: its length plus a margin, at least 1s.
        const speedMs = parseFloat(ex.design.animationSpeed ?? WIDGET_ANIMATION_SPEED) * 1000;
        await page.waitForTimeout(Math.max(1000, speedMs + 500));
        mkdirSync(dirname(imagePath(ex)), { recursive: true });
        await page.screenshot({ path: imagePath(ex) });
        console.log(`rendered ${imageRel(ex)}`);
      } catch (err) {
        console.error(`gallery: banner did not render for "${ex.id}": ${err.message.split('\n')[0]}`);
        failed = true;
      }
      await context.close();
    }
  } finally {
    await browser.close();
  }
  if (failed) process.exit(1);
}

// ---------- main ----------

const [cmd, ...args] = process.argv.slice(2);
if (cmd === 'build') build(args.includes('--check'));
else if (cmd === 'render') await render(args);
else {
  console.error('usage: node scripts/gallery.mjs build [--check] | render [id ...]');
  process.exit(2);
}
