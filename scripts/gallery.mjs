// screenshots, the markdown pages and the HTML pages can never disagree.
// Each example names its banner engine: "v1" examples make up gallery/,
// "v2" examples make up gallery/v2/. The two pages link to each other.
//
//   node scripts/gallery.mjs render [id ...]  screenshot each example to <gallery dir>/img/<id>.png
//                                             (needs playwright: npm i playwright)
//   node scripts/gallery.mjs build            validate, then write README.md + index.html for each gallery
//   node scripts/gallery.mjs build --check    exit 1 if those files are out of date (for CI)
//
