// ---------- build ----------

function build(check) {
  validate({ needImages: true });
  let stale = false;
  const written = [];
  for (const [engine, { dir }] of Object.entries(ENGINES)) {
    for (const [name, content] of Object.entries({ 'README.md': readme(engine), 'index.html': html(engine) })) {
      const rel = `${dir}/${name}`;
      const path = join(root, rel);
      if (check) {
        if (!existsSync(path) || readFileSync(path, 'utf8') !== content) {
          console.error(`stale: ${rel} does not match gallery/examples.json (run: node scripts/gallery.mjs build)`);
          stale = true;
        }
      } else {
        writeFileSync(path, content);
        written.push(rel);
      }
    }
  }
  if (stale) process.exit(1);
  console.log(check ? 'gallery: up to date' : `gallery: wrote ${written.join(', ')}`);
}

