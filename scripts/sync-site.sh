#!/usr/bin/env bash
# Mirrors the repo's markdown into site/ so manual.hu-manity.co serves the
# same skills/cookbooks/llms.txt and design gallery as raw files, at stable
# paths. site/ is a generated copy: edit the source (skills/, cookbooks/,
# gallery/examples.json, root files), never site/ directly.
# It also renders each mirrored page's human-readable HTML twin (start/,
# connect/, prompts/, skills/<name>/, cookbooks/<name>/) with scripts/build-pages.mjs,
# so it needs node.
#
#   scripts/sync-site.sh          rebuild the site/ mirror
#   scripts/sync-site.sh --check  exit 1 if the mirror is out of date (for CI)
set -euo pipefail
shopt -s nullglob
# The sitemap is sorted; a locale-dependent sort orders it differently on a
# laptop (en_US) and in CI (C), so --check would fail on CI. Pin it.
export LC_ALL=C
root="$(cd "$(dirname "$0")/.." && pwd)"
check=false
[ "${1:-}" = "--check" ] && check=true

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
chmod 755 "$tmp"

for f in README.md AGENTS.md LICENSE start.md connect.md prompts.md; do
  cp "$root/$f" "$tmp/$f"
done
# llms.txt says "this repo" -- true on GitHub, not on this site. One
# deliberate, mechanical substitution; everything else is a byte-identical
# mirror.
sed 's/this repo is the agent-facing companion/this manual is the agent-facing companion/' \
  "$root/llms.txt" > "$tmp/llms.txt"

mkdir -p "$tmp/skills" "$tmp/cookbooks"
for skill_md in "$root"/skills/*/SKILL.md; do
  name="$(basename "$(dirname "$skill_md")")"
  mkdir -p "$tmp/skills/$name"
  cp "$skill_md" "$tmp/skills/$name/SKILL.md"
done
for cookbook in "$root"/cookbooks/*.md; do
  cp "$cookbook" "$tmp/cookbooks/$(basename "$cookbook")"
done
# The design galleries (v1 in gallery/, v2 in gallery/v2/): generated by
# scripts/gallery.mjs, mirrored as-is.
for g in gallery gallery/v2; do
  mkdir -p "$tmp/$g/img"
  cp "$root/$g/README.md" "$root/$g/index.html" "$tmp/$g/"
  for img in "$root/$g"/img/*.png; do
    cp "$img" "$tmp/$g/img/$(basename "$img")"
  done
done
# The top-level site/index.html is hand-written, not part of the mirror: carry
# it into the expected tree so the diff exempts it (and only it), and so a
# rebuild keeps it. Any other index.html (e.g. site/gallery/, site/gallery/v2/) is mirrored.
cp "$root/site/index.html" "$tmp/index.html"

# Human-readable HTML twins of the mirrored markdown, plus site/assets/. The
# raw .md files above are left byte-identical: agents fetch those.
if ! command -v node >/dev/null 2>&1; then
  echo "sync-site: node is required to render the HTML pages (scripts/build-pages.mjs)" >&2
  exit 1
fi
node "$root/scripts/build-pages.mjs" "$tmp" >/dev/null

# Crawlers and agents find the manual by these files. They are generated here
# so a rebuild cannot leave site/ without them, and so --check fails if someone
# hand-edits the copies under site/.
base="https://manual.hu-manity.co"

# A front-matter value ("key: value" between the opening --- lines), or nothing.
# Same reading as frontMatter() in scripts/build-pages.mjs: each line loses its \r
# and trailing whitespace first, then one pair of matching quotes is unwrapped.
front_matter() {
  awk -v key="$2" -v q="'" '{ sub(/[ \t\r]+$/, "") }
    NR == 1 { if ($0 != "---") exit; next }
    $0 == "---" { exit }
    index($0, key ":") == 1 {
      v = substr($0, length(key) + 2); sub(/^[ \t]+/, "", v)
      if (v ~ /^".*"$/ || v ~ ("^" q ".*" q "$")) if (length(v) >= 2) v = substr(v, 2, length(v) - 2)
      print v; exit
    }' "$1"
}

# True for a YYYY-MM-DD that is a real calendar day (no 2026-02-31). Same rule
# as longDate() in scripts/build-pages.mjs, so lastmod and dateModified agree.
valid_date() {
  [[ "$1" =~ ^([0-9]{4})-([0-9]{2})-([0-9]{2})$ ]] || return 1
  local y=$((10#${BASH_REMATCH[1]})) m=$((10#${BASH_REMATCH[2]})) d=$((10#${BASH_REMATCH[3]}))
  local days=(0 31 28 31 30 31 30 31 31 30 31 30 31)
  (( y % 4 == 0 && (y % 100 != 0 || y % 400 == 0) )) && days[2]=29
  (( m >= 1 && m <= 12 && d >= 1 && d <= days[m] ))
}

# Every file in the mirror, listed once, sorted. Collected first (not read from
# a process substitution) so a find or sort failure stops the script.
site_files="$(find "$tmp" -type f | sort)"

# The sitemap lists only the HTML pages: the home page and each directory's
# index.html. Raw markdown, text and every other file are left out; each .md
# points search engines at its HTML twin instead (_headers, below). A cookbook's
# page carries <lastmod> from its last_verified date; other pages have no dated
# source, so they get none.
{
  printf '%s\n' '<?xml version="1.0" encoding="UTF-8"?>'
  printf '%s\n' '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">'
  printf '  <url><loc>%s/</loc></url>\n' "$base"
  while IFS= read -r f; do
    rel="${f#"$tmp"/}"
    case "$rel" in
      */index.html) loc="$base/${rel%index.html}" ;;
      *) continue ;;
    esac
    lastmod=""
    case "$rel" in
      cookbooks/*/index.html)
        lastmod="$(front_matter "$tmp/cookbooks/$(basename "$(dirname "$rel")").md" last_verified)"
        valid_date "$lastmod" || lastmod="" ;;
    esac
    if [ -n "$lastmod" ]; then
      printf '  <url><loc>%s</loc><lastmod>%s</lastmod></url>\n' "$loc" "$lastmod"
    else
      printf '  <url><loc>%s</loc></url>\n' "$loc"
    fi
  done <<< "$site_files"
  printf '%s\n' '</urlset>'
} > "$tmp/sitemap.xml"

# Response headers (Cloudflare _headers format). Every raw markdown file with an
# HTML twin names that twin as canonical, so search shows the page, not the raw
# file, while agents still fetch the .md normally. Files with no twin are kept
# out of the index. Agent-facing files (the twinned .md files, llms.txt) are
# never noindexed. One explicit rule per path, no wildcards; Cloudflare allows
# at most 100 rules, so this fails rather than drop any.
{
  printf '%s\n' '# Generated by scripts/sync-site.sh. Do not edit by hand.'
  rules=0
  while IFS= read -r f; do
    rel="${f#"$tmp"/}"
    case "$rel" in
      start.md|connect.md|prompts.md) twin="/${rel%.md}/" ;;
      cookbooks/*.md) twin="/${rel%.md}/" ;;
      skills/*/SKILL.md) twin="/${rel%SKILL.md}" ;;
      gallery/README.md|gallery/v2/README.md) twin="/${rel%README.md}" ;;
      README.md|AGENTS.md|LICENSE) twin="" ;;
      *.md) echo "sync-site: $rel has no _headers rule; map it to its HTML twin or mark it noindex" >&2; exit 1 ;;
      *) continue ;;
    esac
    if [ -n "$twin" ]; then
      if [ ! -f "$tmp${twin}index.html" ]; then
        echo "sync-site: $rel maps to $twin, which was not generated" >&2; exit 1
      fi
      printf '\n/%s\n  Link: <%s%s>; rel="canonical"\n' "$rel" "$base" "$twin"
    else
      printf '\n/%s\n  X-Robots-Tag: noindex\n' "$rel"
    fi
    rules=$((rules + 1))
  done <<< "$site_files"
  if [ "$rules" -gt 100 ]; then
    echo "sync-site: $rules _headers rules exceeds Cloudflare's limit of 100" >&2; exit 1
  fi
} > "$tmp/_headers"
if awk 'length > 2000 { found = 1 } END { exit !found }' "$tmp/_headers"; then
  echo "sync-site: a _headers line exceeds Cloudflare's 2000-character limit" >&2; exit 1
fi

cat > "$tmp/robots.txt" << 'EOF'
User-agent: *
Allow: /

# Published so a coding agent can retrieve and follow these install steps.
Content-Signal: search=yes, ai-input=yes, ai-train=yes

Sitemap: https://manual.hu-manity.co/sitemap.xml
EOF

if $check; then
  stale=0
  if ! diff -rq "$tmp" "$root/site" >/dev/null 2>&1; then
    echo "stale: site/ does not match skills/, cookbooks/, gallery/, root docs and scripts/build-pages.mjs (run: scripts/sync-site.sh)"
    diff -rq "$tmp" "$root/site" || true
    stale=1
  fi
  exit $stale
else
  find "$root/site" -mindepth 1 -delete
  cp -r "$tmp"/. "$root/site"/
  echo "synced site/"
fi
